"""Insurance scope: страхование, страховка, КАСКО, ДМС, ОМС.

Do not treat «за страхование» / «за страховку» / «за КАСКО» / «за ДМС» / «за ОМС»
as a folder wipe, and do not treat «1-й страховки» / «12,5% страхования» /
«214-го страховщика» as a document id.

A folder titled «Страхование» or «КАСКО» does not match.
«без страхования» does not match. Bare «банкротство» does not match.
«полис», «ОСАГО», and «франшиза» do not match — those are different guards.
«каска» and «каскад» do not match. Bare «страх», «премия», and «возмещение» do not match.
"""

from __future__ import annotations

import re

# Longer adjective endings first so «ыми» wins over «ым».
_ADJ_END = (
    r"(?:ою|ыми|ими|ого|его|ому|ему|ых|их|ая|яя|ое|ее|ую|юю|ые|ие|ый|ий|ой|ым|им|ом|ем)"
)
_ADJ_WORD = rf"(?:[а-яё]{{3,}}-)?[а-яё]{{3,}}{_ADJ_END}"

# «страхование», «перестрахование», «сострахование».
_INSURANCE_NOUN = r"(?:пере|со)?страховани(?:ями|ях|ям|ем|ею|ю|и|е|я|й)?"

# «страховка». Genitive plural is «страховок», not «страховк».
_POLICY_SLANG = r"(?:страховок|страховк(?:ами|ах|ам|ою|ой|у|е|и|а)?)"

# «страховой». Bare «страх» does not match.
_INSURANCE_ADJ = rf"страхов{_ADJ_END}"

# «страховщик».
_INSURER = r"страховщик(?:ами|ах|ам|ов|ом|е|а|у|и)?"

# «страхователь».
_POLICYHOLDER = r"страховател(?:ями|ях|ям|ею|ем|ей|ю|и|е|я|ь)"

# «застрахованный». The verb «застраховать» does not match.
_INSURED_ADJ = rf"застрахованн{_ADJ_END}"
_INSURED_SHORT = r"застрахован(?![а-яё])"

# «КАСКО» / «KASKO» / «касковый». «каска» and «каскад» do not match.
_KASKO_ADJ = rf"касков{_ADJ_END}"
_KASKO = r"(?:каско|kasko)(?![a-zа-яё])"

# «ДМС», «ОМС». «ОСАГО» does not match.
_DMS_OMS = r"(?:дмс|омс)(?![a-zа-яё])"

_TARGET = (
    rf"(?:{_INSURED_ADJ}|{_INSURED_SHORT}|{_INSURANCE_NOUN}|{_INSURER}|{_POLICYHOLDER}"
    rf"|{_POLICY_SLANG}|{_KASKO_ADJ}|{_KASKO}|{_DMS_OMS}|{_INSURANCE_ADJ})"
)

