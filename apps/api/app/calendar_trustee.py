"""Trustee, moratorium, and asset-realization scope.

Do not treat «за конкурсного управляющего» / «за внешнего управляющего» /
«за временного управляющего» / «за финансового управляющего» /
«за арбитражного управляющего» / «за мораторий» / «за реализацию имущества»
as a folder wipe, and do not treat «1-го конкурсного управляющего» /
«100 реализации имущества» as a document id.

A folder titled «Конкурсный управляющий», «Мораторий», or «Реализация имущества»
does not match. «без конкурсного управляющего» does not match. Bare
«банкротство» does not match. «внешнее управление», «финансовое оздоровление»,
«конкурсное производство», and «исполнительный лист» are not these phrases.
"""

from __future__ import annotations

import re

# «конкурсный управляющий». «конкурсное производство» has no «управляющ».
_KONK = r"конкурсн(?:ыми|ого|ому|ые|ых|ым|ом|ая|ой|ую|ое|ый)"
# «внешний управляющий». «внешнее управление» is «управлени», not «управляющ».
_VNESH = r"внешн(?:ими|его|ему|ие|их|ым|им|ем|ее|ий)"
# «временный управляющий» and the adverb «временно управляющий».
_VREM = r"временн(?:ыми|ого|ому|ые|ых|ым|ом|ый|о)"
# «финансовый управляющий». «финансовое оздоровление» has no «управляющ».
_FIN = r"финансов(?:ыми|ого|ому|ые|ых|ым|ом|ый|ое)"
_ARB = r"арбитражн(?:ыми|ого|ому|ые|ых|ым|ом|ая|ой|ую|ое|ый)"
_OFFICER = r"управляющ(?:ими|его|ему|ие|их|ая|ую|ею|ей|ий|им|ем)"
_TRUSTEE = rf"(?:{_KONK}|{_VNESH}|{_VREM}|{_FIN}|{_ARB})\s+{_OFFICER}"

# «мораторий». «моральный» does not contain this stem.
_MORAT = r"моратори(?:ями|ях|ям|ев|ем|ю|и|я|й)"

# «реализация имущества». Bare «реализация» (плана, проекта) does not match.
_REALIZ = r"реализаци(?:ями|ях|ям|ею|ей|ю|и|е|я|й)"
_IMUSH = r"имуществ(?:ами|ах|ам|ом|у|е|а|о)"

_DEMONSTRATIVE = (
    r"(?:этими|этих|этот|этого|этому|этой|этом|эта|эту|эти|это|"
    r"прошл\w{0,4}|текущ\w{0,4}|данн\w{0,4}|сво\w{0,4})\s+"
)

_WORD_ORDINAL = (
    r"(?:перв(?:ое|ого|ому|ым|ом|ая|ую|ой|ый|ые|ых|ыми)|втор(?:ое|ого|ому|ым|ом|ая|ую|ой|ый|ые|ых|ыми)|"
    r"трет(?:ье|ьего|ьему|ьим|ьем|ья|ью|ьей|ий|ьи|ьих|ьими)|четв[её]рт(?:ое|ого|ому|ым|ом|ая|ую|ой|ый|ые|ых|ыми))"
)

_ADJ_WORD = (
    r"(?:[а-яё]{3,}-)?[а-яё]{3,}(?:ыми|ими|ый|ий|ой|ая|яя|ое|ее|ые|ие|ого|его|ому|ему|ым|им|ом|ем|ую|юю|ых|их)"
)

_REALIZ_IMUSH = rf"{_REALIZ}\s+(?:{_ADJ_WORD}\s+){{0,2}}{_IMUSH}"
_TARGET = rf"(?:{_TRUSTEE}|{_MORAT}|{_REALIZ_IMUSH})"

_WHOLE = r"(?<![а-яё])(?:всеми|всех|всему|всего|всей|всем|весь|вся|всё|все|всю)"

# Words that sit between the preposition and the officer / moratorium / sale.
# «папке» and «делу» are not here, so a folder titled «Мораторий» does not match.
_NOUN_QUAL = (
    r"(?<![а-яё])(?:процедур(?:ами|ах|ам|ою|ой|у|е|ы|а)?"
    r"|стади(?:ями|ях|ям|ей|ею|ю|и|е|я)?"
    r"|введени(?:ями|ях|ям|ем|ею|ю|и|е|я|й)?"
    r"|открыти(?:ями|ях|ям|ем|ею|ю|и|е|я|й)?"
    r"|возбуждени(?:ями|ях|ям|ем|ею|ю|и|е|я|й)?"
    r"|завершени(?:ями|ях|ям|ем|ею|ю|и|е|я|й)?"
    r"|продлени(?:ями|ях|ям|ем|ею|ю|и|е|я|й)?"
    r"|назначени(?:ями|ях|ям|ем|ею|ю|и|е|я|й)?"
    r"|утверждени(?:ями|ях|ям|ем|ею|ю|и|е|я|й)?"
    r"|отстранени(?:ями|ях|ям|ем|ею|ю|и|е|я|й)?"
    r"|вознаграждени(?:ями|ях|ям|ем|ею|ю|и|е|я|й)?"
    r"|ходатайств(?:ами|ах|ам|ов|ом|е|а|у|ы)?"
    r"|заявлени(?:ями|ях|ям|ем|ею|ю|и|е|я|й)?"
    r"|жалоб(?:ами|ах|ам|ой|у|е|ы|а)?"
    r"|отчет(?:ами|ах|ам|ов|ом|е|а|у|ы)?"
    r"|кандидатур(?:ами|ах|ам|ою|ой|у|е|ы|а)?"
    r"|деятельност(?:ями|ях|ям|ью|ей|и|ь)?"
    r"|бездействи(?:ями|ях|ям|ем|ею|ю|и|е|я|й)?"
    r"|действи(?:ями|ях|ям|ем|ею|ю|и|е|я|й)?"
    r"|период(?:ами|ах|ам|ов|ом|е|а|у|ы)?"
    r"|срок(?:ами|ах|ам|ов|ом|е|а|у|и)?"
    r"|торг(?:ами|ах|ам|ов|ом|и|е|а|у)?"
    r"|ход(?:ами|ах|ам|ов|ом|е|а|у|ы)?"
    r"|рамк(?:ами|ах|ам|ою|ой|у|е|и|а)?)(?![а-яё])"
)

_QUAL = rf"(?:{_DEMONSTRATIVE}|{_WORD_ORDINAL}\s+|{_WHOLE}\s+|{_NOUN_QUAL}\s+|{_ADJ_WORD}\s+)"

_ORDINAL_SUFFIX = r"(?:го|му|ой|ую|й|е|я|ю|о|м|х|ем)"

_PREP = re.compile(
    rf"(?<![а-яё])(?:под|об|во|ко|со|от|для|перед|после|при|за|на|по|из|к|в|с|о)\s+"
    rf"(?:{_QUAL}){{0,3}}(?<!без\s)(?<![а-яё]){_TARGET}(?![а-яё])",
    re.IGNORECASE,
)

_DURING = re.compile(
    rf"во\s+время\s+(?:{_QUAL}){{0,3}}(?<![а-яё]){_TARGET}(?![а-яё])",
    re.IGNORECASE,
)

_DEMONSTRATIVE_SCOPE = re.compile(
    rf"(?:этими|этих|этот|этого|этому|этой|этом|эта|эту|эти|это|"
    r"прошлые|прошлых|прошлый|прошлого|прошлая|прошлую|прошлое|"
    r"текущие|текущих|текущий|текущего|текущая|текущую|текущее|"
    r"данные|данных|данного)\s+"
    rf"(?:{_QUAL}){{0,2}}(?<![а-яё]){_TARGET}(?![а-яё])",
    re.IGNORECASE,
)

_ORDINAL_WORD = re.compile(
    rf"(?:об|за|в|во|на|по|с|со|из|о|от|для|под|к|ко)\s+{_WORD_ORDINAL}\s+(?:{_QUAL}){{0,2}}(?<![а-яё]){_TARGET}(?![а-яё])"
    rf"|\b{_WORD_ORDINAL}\s+(?:{_QUAL}){{0,2}}(?<![а-яё]){_TARGET}(?![а-яё])",
    re.IGNORECASE,
)

_ORDINAL_NUM = re.compile(
    rf"\b\d{{1,2}}(?!\d)(?:-?{_ORDINAL_SUFFIX})?\s*(?:{_QUAL}){{0,2}}(?<![а-яё]){_TARGET}(?![а-яё])",
    re.IGNORECASE,
)

_SCOPED_AMOUNT = re.compile(
    rf"\b\d+(?:\s*[.,]\s*\d+)?\s*(?:{_QUAL}){{0,2}}(?<![а-яё]){_TARGET}(?![а-яё])",
    re.IGNORECASE,
)

_DOCS = re.compile(
    rf"(?:документ|файл)\w*\s+(?:{_QUAL}){{0,3}}(?<![а-яё]){_TARGET}(?![а-яё])",
    re.IGNORECASE,
)


