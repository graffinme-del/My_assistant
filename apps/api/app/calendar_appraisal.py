def _prepare(text: str) -> str:
    return (text or "").replace("ё", "е").replace("Ё", "Е")


def mask_appraisal_ordinals(text: str) -> str:
    """Replace «1-й оценки» so the digit is not a document id.

    Amounts run first so «12,5% оценки» is one token. The ordinal pass
    would otherwise keep «12» and only hide the «5».
    """
    raw = _prepare(text)
    masked = _SCOPED_AMOUNT.sub(" ", raw)
    return _ORDINAL_NUM.sub(" ", masked)


def looks_like_appraisal_scoped_document_request(text: str) -> bool:
    """True when the user scoped files to an appraisal, an appraiser, or an appraisal report."""
    raw = _prepare(text)
    return bool(
        _PREP.search(raw)
        or _DURING.search(raw)
        or _DEMONSTRATIVE_SCOPE.search(raw)
        or _ORDINAL_WORD.search(raw)
        or _ORDINAL_NUM.search(raw)
        or _SCOPED_AMOUNT.search(raw)
        or _DOCS.search(raw)
    )


def appraisal_blocks_bulk_document_mutation(
    text: str, *, explicit_document_ids: list[int] | None = None
) -> bool:
    """Refuse folder-wide delete/move when an appraisal scope is present.

    Chat treated «удали все документы за оценку в этой папке» as
    wipe-the-folder because «все документы» matched wants_all and «в этой
    папке» (or a case number, or «текущ» / «открыт») selected the case.
    «удали документы 1-й оценки» took the first digit as a document id.
    The same path hits «по договору оценки» and «214-го оценщика».
    """
    if explicit_document_ids:
        return False
    return looks_like_appraisal_scoped_document_request(text)
