_QUAL = rf"(?:{_DEMONSTRATIVE}|{_WORD_ORDINAL}\s+|{_WHOLE}\s+|{_NOUN_QUAL}\s+|{_ADJ_WORD}\s+)"
_Q = r"(?:[«»\"'„“”]\s*)?"

_ORDINAL_SUFFIX = r"(?:го|му|ой|ую|й|е|я|ю|о|м|х|ем)"

# «переоценка» / «недооценка» / «дооценка» share the «оценк» stem.
_PREFIX = r"(?:пере|недо|само|до)"

# «оценщица» uses «ц», not «к». The extra «а» in the surname «Оценщикова» stays outside.
_APPRAISER = r"оценщик(?:ами|ах|ам|ов|ом|у|е|и|а)?"
_APPRAISER_F = r"оценщиц(?:ами|ах|ам|ею|ей|у|е|ы|а)?"
# «оценок» drops the «к». Verbs «оценить» / «оценивать» do not match.
_APPRAISAL_NOUN = rf"{_PREFIX}?оцен(?:к(?:ами|ах|ам|ою|ой|у|е|и|а)?|ок)"
_APPRAISAL_ADJ = rf"{_PREFIX}?оценочн{_ADJ_END}"

_TARGET = rf"(?:{_APPRAISER_F}|{_APPRAISER}|{_APPRAISAL_ADJ}|{_APPRAISAL_NOUN})"
_SCOPE = _TARGET

