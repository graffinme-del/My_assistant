_DOCS = re.compile(
    rf"(?:документ|файл)\w*\s+(?:{_NEG_WORD}{_Q}{_QUAL}){{0,3}}{_Q}(?<![a-zа-яё]){_NEG}{_SCOPE}(?![a-zа-яё])",
    re.IGNORECASE,
)


