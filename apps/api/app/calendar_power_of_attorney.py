def _prepare(text: str) -> str:
    return (text or "").replace("ё", "е").replace("Ё", "Е")


def mask_power_of_attorney_ordinals(text: str) -> str:
    """Replace «1-я доверенность» so the digit is not a document id.

    Amounts run first so «12,5% доверенности» is one token. The ordinal
    pass would otherwise keep «12» and only hide the «5».
    """
    raw = _prepare(text)
    masked = _SCOPED_AMOUNT.sub(" ", raw)
    return _ORDINAL_NUM.sub(" ", masked)


def looks_like_power_of_attorney_scoped_document_request(text: str) -> bool:
    """True when the user scoped files to a power of attorney («доверенность»)."""
    raw = _prepare(text)
    return bool(
        _PREP.search(raw)
        or _DURING.search(raw)
        or _DEMONSTRATIVE_SCOPE.search(raw)
        or _ORDINAL_WORD.search(raw)
        or _ORDINAL_NUM.search(raw)
        or _SCOPED_AMOUNT.search(raw)
        or _DOCS.search(raw)
    )


def power_of_attorney_blocks_bulk_document_mutation(
    text: str, *, explicit_document_ids: list[int] | None = None
) -> bool:
    """Refuse folder-wide delete/move when a power-of-attorney scope is present.

    Chat treated «удали все документы за доверенность в этой папке» as
    wipe-the-folder because «все документы» matched wants_all and «в этой
    папке» (or a case number, or «текущ» / «открыт») selected the case.
    «удали документы 1-я доверенность» took the first digit as a document id.
    «удали документы по отзыву доверенности» took the tail as a PDF-text hint.
    «претензия» and «упущенная прибыль» are separate guards.
    """
    if explicit_document_ids:
        return False
    return looks_like_power_of_attorney_scoped_document_request(text)
