    r"|взнос(?:ами|ах|ам|ов|ом|е|а|у|ы)?"
    r"|выкуп(?:ами|ах|ам|ов|ом|е|а|у|ы)?"
    r"|график(?:ами|ах|ам|ов|ом|е|а|у|и)?"
    r"|процент(?:ами|ах|ам|ов|ом|е|а|у|ы)?"
    r"|долг(?:ами|ах|ам|ов|ом|е|а|у|и)?"
    r"|учет(?:ами|ах|ам|ов|ом|е|а|у|ы)?"
    r"|авал(?:ями|ях|ям|ей|ем|ю|е|я|и|ь)"
    r"|новаци(?:ями|ях|ям|ей|ею|ей|ю|и|е|я|й)?"
    r"|замен(?:ами|ах|ам|ою|ой|у|е|ы|а)?"
    r"|тел(?:ами|ах|ам|ом|о|у|е|а)"
