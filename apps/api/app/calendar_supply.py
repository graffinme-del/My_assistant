_ORDINAL_SUFFIX = r"(?:го|му|ой|ую|й|е|я|ю|о|м|х|ем)"

_PREP = re.compile(
    rf"(?<![а-яё])(?:под|об|во|ко|со|от|для|перед|после|при|за|на|по|из|к|в|с|о)\s+"
    rf"(?:{_Q}{_QUAL}){{0,3}}(?<!без\s){_Q}(?<![a-zа-яё]){_SCOPE}(?![a-zа-яё])",
    re.IGNORECASE,
)

_DURING = re.compile(
    rf"во\s+время\s+(?:{_Q}{_QUAL}){{0,3}}{_Q}(?<![a-zа-яё]){_SCOPE}(?![a-zа-яё])",
    re.IGNORECASE,
)

