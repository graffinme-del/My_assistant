def _prepare(text: str) -> str:
    return (text or "").replace("ё", "е").replace("Ё", "Е")


def mask_supply_contract_ordinals(text: str) -> str:
    """Replace «1-й поставки» so the digit is not a document id.

    Amounts run first so «12,5% подряда» is one token. The ordinal pass
    would otherwise keep «12» and only hide the «5».
    """
    raw = _prepare(text)
    masked = _SCOPED_AMOUNT.sub(" ", raw)
    return _ORDINAL_NUM.sub(" ", masked)


def looks_like_supply_contract_scoped_document_request(text: str) -> bool:
    """True when the user scoped files to supply, a work contract, or a sale."""
    raw = _prepare(text)
    return bool(
        _PREP.search(raw)
        or _DURING.search(raw)
        or _DEMONSTRATIVE_SCOPE.search(raw)
        or _ORDINAL_WORD.search(raw)
        or _ORDINAL_NUM.search(raw)
        or _SCOPED_AMOUNT.search(raw)
        or _DOCS.search(raw)
        or _DOCS_BARE.search(raw)
    )


def supply_contract_blocks_bulk_document_mutation(
    text: str, *, explicit_document_ids: list[int] | None = None
) -> bool:
    """Refuse folder-wide delete/move when a supply, contract, or sale scope is present.

    Chat treated «удали все документы за поставку в этой папке» as wipe-the-folder
    because «все документы» matched wants_all and «в этой папке» (or a case
    number, or «текущ» / «открыт») selected the case. «удали документы 1-й
    поставки» took the first digit as a document id. The same path hits
    «за подряд», «за подрядчика», «за договор купли-продажи», and «за поставщика».
    """
    if explicit_document_ids:
        return False
    return looks_like_supply_contract_scoped_document_request(text)
