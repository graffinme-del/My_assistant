def _prepare(text: str) -> str:
    return (text or "").replace("ё", "е").replace("Ё", "Е")


def mask_tax_charge_ordinals(text: str) -> str:
    """Replace «2-НДФЛ» / «13% НДФЛ» / «1-й недоимки» so the digit is not a document id.

    Form numbers run first: «2-НДФЛ» is not an ordinal suffix, and the amount
    pass would keep «2». Amounts run before ordinals so «12,5% недоимки» is
    one token. The ordinal pass would otherwise keep «12» and only hide the «5».
    """
    raw = _prepare(text)
    masked = _NDFL_FORM_TOKEN.sub(" ", raw)
    masked = _SCOPED_AMOUNT.sub(" ", masked)
    return _ORDINAL_NUM.sub(" ", masked)


def looks_like_tax_charge_scoped_document_request(text: str) -> bool:
    """True when the user scoped files to NDFL, FTS, USN, arrears, or an extra assessment."""
    raw = _prepare(text)
    return bool(
        _PREP.search(raw)
        or _DURING.search(raw)
        or _DEMONSTRATIVE_SCOPE.search(raw)
        or _ORDINAL_WORD.search(raw)
        or _ORDINAL_NUM.search(raw)
        or _SCOPED_AMOUNT.search(raw)
        or _DOCS.search(raw)
    )


def tax_charge_blocks_bulk_document_mutation(
    text: str, *, explicit_document_ids: list[int] | None = None
) -> bool:
    """Refuse folder-wide delete/move when a tax-charge scope is present.

    Chat treated «удали все документы за НДФЛ в этой папке» as wipe-the-folder
    because «все документы» matched wants_all and «в этой папке» (or a case
    number, or «текущ» / «открыт») selected the case. «удали документы 2-НДФЛ»
    and «удали документы 6% УСН» took the first digit as a document id. The
    same path hits «за недоимку», «по доначислению», and «214-го доначисления».
    «налог» / «НДС» / «инкассо» are a separate guard and are not matched here.
    """
    if explicit_document_ids:
        return False
    return looks_like_tax_charge_scoped_document_request(text)
