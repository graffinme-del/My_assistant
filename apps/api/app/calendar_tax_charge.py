_SCOPED_AMOUNT = re.compile(
    rf"\b\d+(?:\s*[.,]\s*\d+)?\s*%?\s*(?:{_Q}{_QUAL}){{0,2}}{_Q}(?<![a-zа-яё]){_SCOPE}(?![a-zа-яё])",
    re.IGNORECASE,
)

# Hyphenated and glued form numbers. The amount/ordinal masks keep the digit
# when the only separator is «-» and the next token is «НДФЛ».
_NDFL_FORM_TOKEN = re.compile(
    rf"\b\d{{1,2}}(?!\d)\s*[-–—]?\s*ндфл{_NDFL_END}(?![a-zа-яё])",
    re.IGNORECASE,
)

_DOCS = re.compile(
    rf"(?:документ|файл)\w*\s+(?:{_Q}{_QUAL}){{0,3}}{_Q}(?<![a-zа-яё]){_TARGET}(?![a-zа-яё])",
    re.IGNORECASE,
)


