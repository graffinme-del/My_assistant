"""Franchise, dividend, and subsidy scope.

Do not treat «за франшизу» / «за дивиденд» / «за субсидию» as a folder wipe,
and do not treat «1-го дивиденда» / «100 субсидии» / «12,5% франшизы» /
«214-го дивиденда» as a document id.

A folder titled «Франшиза», «Дивиденды», or «Субсидия» does not match.
«без франшизы» does not match. Bare «банкротство» does not match.
«субсидиарная» / «субсидиарка» do not match — that is a different word.
«франчайзинг» does not match. «кредит», «овердрафт», and «рента» stay
with their own guards.
"""

from __future__ import annotations

import re

# Longer adjective endings first so «ыми» wins over «ым».
_ADJ_END = (
    r"(?:ою|ыми|ими|ого|его|ому|ему|ых|их|ая|яя|ое|ее|ую|юю|ые|ие|ый|ий|ой|ым|им|ом|ем)"
)
_ADJ_WORD = rf"(?:[а-яё]{{3,}}-)?[а-яё]{{3,}}{_ADJ_END}"

# «франшизный». The noun boundary rejects a following letter.
_FRANCHISE_ADJ = rf"франшизн{_ADJ_END}"
_FRANCHISE_NOUN = r"франшиз(?:ою|ами|ах|ам|ой|у|е|ы|а)?"
_FRANCHISE = rf"(?:{_FRANCHISE_ADJ}|{_FRANCHISE_NOUN})"

# «дивидендный».
_DIVIDEND_ADJ = rf"дивидендн{_ADJ_END}"
_DIVIDEND_NOUN = r"дивиденд(?:ами|ах|ам|ов|ом|е|а|у|ы)?"
_DIVIDEND = rf"(?:{_DIVIDEND_ADJ}|{_DIVIDEND_NOUN})"

# «субсидирование», «субсидированный», «субсидируемый».
# «субсидиарная» fails: after «субсиди» comes «а», which is not a noun ending,
# and «субсидиарн» is not «субсидированн» / «субсидируем».
_SUBSIDY_PROCESS = r"субсидировани(?:ями|ях|ям|ем|ею|ю|и|е|я|й)?"
_SUBSIDY_PARTICIPLE = rf"субсидированн{_ADJ_END}"
_SUBSIDY_ADJ = rf"субсидируем{_ADJ_END}"
_SUBSIDY_NOUN = r"субсиди(?:ями|ях|ям|ей|ею|ю|и|е|я|й)?"
_SUBSIDY = rf"(?:{_SUBSIDY_PROCESS}|{_SUBSIDY_PARTICIPLE}|{_SUBSIDY_ADJ}|{_SUBSIDY_NOUN})"

_TARGET = rf"(?:{_FRANCHISE}|{_DIVIDEND}|{_SUBSIDY})"

_DEMONSTRATIVE = (
    r"(?:этими|этих|этот|этого|этому|этой|этом|эта|эту|эти|это|"
    r"(?<![а-яё])(?:теми|тех|тому|того|той|тот|тем|том|та|ту|те|то)|"
    r"прошл\w{0,4}|текущ\w{0,4}|данн\w{0,4}|сво\w{0,4})\s+"
)

_WORD_ORDINAL = (
    r"(?:перв(?:ое|ого|ому|ым|ом|ая|ую|ой|ый|ые|ых|ыми)|втор(?:ое|ого|ому|ым|ом|ая|ую|ой|ый|ые|ых|ыми)|"
    r"трет(?:ье|ьего|ьему|ьим|ьем|ья|ью|ьей|ий|ьи|ьих|ьими)|четв[её]рт(?:ое|ого|ому|ым|ом|ая|ую|ой|ый|ые|ых|ыми))"
)

_WHOLE = r"(?<![а-яё])(?:всеми|всех|всему|всего|всей|всем|весь|вся|всё|все|всю)"

