    r"|ставк(?:ами|ах|ам|ою|ой|у|е|и|а)?"
    r"|залог(?:ами|ах|ам|ов|ом|е|а|у|и)?"
    r"|тел(?:ами|ах|ам|ом|о|у|е|а)"
