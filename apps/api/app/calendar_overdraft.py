def _prepare(text: str) -> str:
    return (text or "").replace("ё", "е").replace("Ё", "Е")


def mask_overdraft_ordinals(text: str) -> str:
    """Replace «1-го овердрафта» so the digit is not a document id.

    Amounts run first so «12,5 ренты» is one token. The ordinal pass
    would otherwise keep «12» and only hide the «5».
    """
    raw = _prepare(text)
    masked = _SCOPED_AMOUNT.sub(" ", raw)
    return _ORDINAL_NUM.sub(" ", masked)


def looks_like_overdraft_scoped_document_request(text: str) -> bool:
    """True when the user scoped files to an overdraft, annuity, or ссуда."""
    raw = _prepare(text)
    return bool(
        _PREP.search(raw)
        or _DURING.search(raw)
        or _DEMONSTRATIVE_SCOPE.search(raw)
        or _ORDINAL_WORD.search(raw)
        or _ORDINAL_NUM.search(raw)
        or _SCOPED_AMOUNT.search(raw)
        or _DOCS.search(raw)
    )


def overdraft_blocks_bulk_document_mutation(
    text: str, *, explicit_document_ids: list[int] | None = None
) -> bool:
    """Refuse folder-wide delete/move when an overdraft, annuity, or ссуда scope is present.

    Chat treated «удали все документы за овердрафт в этой папке» as wipe-the-folder
    because «все документы» matched wants_all and «в этой папке» (or a case
    number, or «текущ» / «открыт») selected the case. «удали документы 1-го
    овердрафта» took the first digit as a document id. The same path hits
    «за ренту» and «за ссуду».
    """
    if explicit_document_ids:
        return False
    return looks_like_overdraft_scoped_document_request(text)
