"""Credit / rent / mortgage chat must not wipe a folder.

Pre-fix, handle_delete_documents_chat treated «все документы» plus «в этой папке»
(or a case number, or «текущ» / «открыт») as wipe-the-folder and parsed
«1-го кредита» as document id 1. The calendar period parser does not recognize
these phrases.

«кредитор» and «аккредитив» belong to other guards or stay unmatched.
A folder titled «Кредит» is not this guard. Bare «банкротство» is not this guard.
«заем» / «займ» stay with the loan guard. «залог» alone is not this guard.
"""

from __future__ import annotations

import re
import unittest
